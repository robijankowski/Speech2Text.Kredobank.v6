def test_scenario(scenario_name, conversation_text):
    """Test a single scenario and print the results."""
    print(f"\n{'='*60}")
    print(f"TESTING {scenario_name.upper()}")
    print(f"{'='*60}")
    
    try:
        # Generate summary
        summary = generate_crm_summary_o4(conversation_text)
        print(summary)
        
    except Exception as e:
        print(f"ERROR: {str(e)}")
        
    print(f"\n{'='*60}")

def test_all_scenarios():
    """Test all sample scenarios."""
    print("CRM SUMMARY FUNCTION TEST")
    print("Testing improved generate_crm_summary_o4 function")
    
    for scenario_name, conversation in SAMPLE_CONVERSATIONS.items():
        test_scenario(scenario_name, conversation)
    
    print("\nTesting completed!")

def test_single_scenario(scenario_name):
    """Test a single scenario by name."""
    if scenario_name in SAMPLE_CONVERSATIONS:
        test_scenario(scenario_name, SAMPLE_CONVERSATIONS[scenario_name])
    else:
        print(f"Scenario '{scenario_name}' not found.")
        print(f"Available scenarios: {list(SAMPLE_CONVERSATIONS.keys())}")

if __name__ == "__main__":
    # Check if a specific scenario was requested
    if len(sys.argv) > 1:
        scenario_name = sys.argv[1]
        test_single_scenario(scenario_name)
    else:
        # Test all scenarios
        test_all_scenarios()